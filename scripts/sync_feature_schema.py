"""Keep fresh-install and manual migration SQL equal to startup feature SQL."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MODULES = ("mobile-schema", "account-features", "account-integration", "account-push-policy",
           "conversation-features", "expressive-features", "call-features", "quality-features")
MARKER = "-- BEGIN GENERATED REMAINING FEATURE SCHEMA\n"


def feature_schema():
    prerequisites = """ALTER TABLE messages ADD COLUMN IF NOT EXISTS read_by jsonb NOT NULL DEFAULT '[]';
ALTER TABLE messages ADD COLUMN IF NOT EXISTS is_post boolean NOT NULL DEFAULT false;
"""
    modules = "\n".join(
        f"-- Source: api/{name}.sql\n" + (ROOT / "api" / f"{name}.sql").read_text(encoding="utf-8").rstrip() + "\n"
        for name in MODULES
    )
    web_push = re.search(r"export const webPushSchema = `([^`]+)`;", (ROOT / "api/web-push.js").read_text(encoding="utf-8"))
    if not web_push:
        raise RuntimeError("Missing web push schema literal")
    return prerequisites + modules + "\n-- Source: api/web-push.js webPushSchema\n" + web_push.group(1) + "\n"


if __name__ == "__main__":
    schema = feature_schema()
    initial = ROOT / "db" / "init.sql"
    original = initial.read_text(encoding="utf-8").split(MARKER)[0].rstrip()
    initial.write_text(original + "\n\n" + MARKER + schema, encoding="utf-8", newline="\n")
    (ROOT / "db/migrations/20261023_remaining_features.sql").write_text(
        "-- Generated by scripts/sync_feature_schema.py. Idempotent; preserve existing data.\n" + schema,
        encoding="utf-8", newline="\n",
    )
